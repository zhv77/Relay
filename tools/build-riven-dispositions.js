'use strict';

// Regenerates src/riven-dispositions.js from WFCD's item export. Run after a disposition update.
const fs = require('node:fs');
const path = require('node:path');

const SOURCE = 'https://raw.githubusercontent.com/WFCD/warframe-items/master/data/json/';
const FILES = ['Primary', 'Secondary', 'Melee', 'Arch-Gun', 'Arch-Melee'];

(async () => {
  const table = {};
  for (const file of FILES) {
    const items = await (await fetch(`${SOURCE}${file}.json`)).json();
    for (const item of items) {
      if (typeof item.omegaAttenuation === 'number') table[item.name] = Math.round(item.omegaAttenuation * 100) / 100;
    }
  }
  const sorted = Object.fromEntries(Object.entries(table).sort(([a], [b]) => a.localeCompare(b)));
  const body = `'use strict';\n\n// Generated by tools/build-riven-dispositions.js from WFCD warframe-items.\nmodule.exports = ${JSON.stringify(sorted, null, 2)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'riven-dispositions.js'), body);
  console.log(`${Object.keys(sorted).length} weapons`);
})();
